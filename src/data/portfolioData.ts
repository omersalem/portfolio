import {
  NAV_ITEMS_EN,
  NAV_ITEMS_AR,
  PROJECTS_EN,
  PROJECTS_AR,
  INFRASTRUCTURE_NODES_EN,
  INFRASTRUCTURE_NODES_AR,
  CAREER_TIMELINE_EN,
  CAREER_TIMELINE_AR,
  CORE_METRICS_EN,
  CORE_METRICS_AR,
  TECH_SKILL_CATEGORIES_EN,
  TECH_SKILL_CATEGORIES_AR,
  CAPABILITY_GROUPS_EN,
  CAPABILITY_GROUPS_AR,
  PROJECT_CASE_STUDIES_EN,
  PROJECT_CASE_STUDIES_AR,
  UI_TEXT,
} from './translations';

export * from './translations';

// Default backward-compatible exports
export const NAV_ITEMS = NAV_ITEMS_EN;
export const PROJECTS = PROJECTS_EN;
export const INFRASTRUCTURE_NODES = INFRASTRUCTURE_NODES_EN;
export const CAREER_TIMELINE = CAREER_TIMELINE_EN;
export const CORE_METRICS = CORE_METRICS_EN;
export const TECH_SKILL_CATEGORIES = TECH_SKILL_CATEGORIES_EN;
export const CAPABILITY_GROUPS = CAPABILITY_GROUPS_EN;
export const PROJECT_CASE_STUDIES = PROJECT_CASE_STUDIES_EN;

export const getPortfolioData = (language: 'en' | 'ar') => {
  const isAr = language === 'ar';
  return {
    navItems: isAr ? NAV_ITEMS_AR : NAV_ITEMS_EN,
    projects: isAr ? PROJECTS_AR : PROJECTS_EN,
    infrastructureNodes: isAr ? INFRASTRUCTURE_NODES_AR : INFRASTRUCTURE_NODES_EN,
    careerTimeline: isAr ? CAREER_TIMELINE_AR : CAREER_TIMELINE_EN,
    coreMetrics: isAr ? CORE_METRICS_AR : CORE_METRICS_EN,
    techSkillCategories: isAr ? TECH_SKILL_CATEGORIES_AR : TECH_SKILL_CATEGORIES_EN,
    capabilityGroups: isAr ? CAPABILITY_GROUPS_AR : CAPABILITY_GROUPS_EN,
    caseStudies: isAr ? PROJECT_CASE_STUDIES_AR : PROJECT_CASE_STUDIES_EN,
    ui: UI_TEXT[language],
  };
};
